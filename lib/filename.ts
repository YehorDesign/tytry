/**
 * Имя файла для рендера. Принцип: НЕ переименовываем то, что дал юзер —
 * убираем только то, что файловая система реально запрещает
 * (< > : " / \ | ? * и управляющие символы). Пробелы, дефисы, точки,
 * кириллица и регистр сохраняются как есть.
 */

// Windows: эти символы запрещены в именах файлов; на mac/linux мешает только "/"
const ILLEGAL = new RegExp('[<>:"/\\\\|?*\\u0000-\\u001f]', "g");
// Windows: зарезервированные имена устройств
const RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])$/i;

// длинные имена креативов резать нельзя, но и путь длиннее MAX_PATH (260)
// Windows не переварит — 120 символов имени оставляют запас на папку и суффиксы
export function sanitizeFileName(name: string, maxLen = 120): string {
  let out = (name ?? "")
    .replace(ILLEGAL, "_")
    .replace(/\s+/g, " ")
    .trim()
    .slice(0, maxLen)
    // Windows не даёт именам оканчиваться точкой или пробелом
    .replace(/[. ]+$/, "");
  if (RESERVED.test(out)) out = `_${out}`;
  return out;
}
